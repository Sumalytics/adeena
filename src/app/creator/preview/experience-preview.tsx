"use client";

import { useState } from "react";
import type { ExperienceManifest } from "@adeena/experience-schema";
import type { CreatorVisualExperience } from "@/experience/visual-director/association";
import type { NarrationMediaTrack } from "@/experience/visual-director/audio-playback";
import { VisualScenePlayer } from "@/experience/visual-director/visual-player";
import { draftPresentation } from "@/experience/present";
import { PlayerApp } from "@/player/player-app";
import { cssRenderer } from "@/player/renderer";
import styles from "./creator-studio.module.css";

export function ExperiencePreview({ manifest, notice, visual = null }: { manifest: ExperienceManifest; notice: string; visual?: CreatorVisualExperience | null }) {
  const [showLegacy, setShowLegacy] = useState(false);
  if (!visual || showLegacy) return <PlayerApp manifest={manifest} presentation={draftPresentation(manifest, notice)} renderer={cssRenderer} />;
  if (visual.status !== "ready") return (
    <section className={styles.visualUnavailable} role="status">
      <h1>{manifest.title}</h1><p>{visual.message}</p>
      <button type="button" onClick={() => setShowLegacy(true)}>Open original playable draft</button>
    </section>
  );
  return <CreatorVisualPreview visual={visual} title={manifest.title} />;
}

function CreatorVisualPreview({ visual, title }: { visual: Extract<CreatorVisualExperience, { status: "ready" }>; title: string }) {
  const [sceneIndex, setSceneIndex] = useState(0);
  const scene = visual.association.blueprint.scenes[sceneIndex];
  const bindings = new Map(visual.narration.map((item) => [item.segmentId, item]));
  const completeAudio = scene.narration.every((segment) => bindings.has(segment.id));
  const narrationMedia: NarrationMediaTrack[] | undefined = completeAudio ? scene.narration.map((segment) => {
    const binding = bindings.get(segment.id)!;
    return { playback: binding.playback, source: binding.source, plannedStartMs: segment.startMs, plannedDurationMs: segment.durationMs };
  }) : undefined;
  return (
    <section className={styles.visualExperience} aria-labelledby="visual-experience-title">
      <header className={styles.visualHeading}>
        <div><p className={styles.visualEyebrow}>Animated learning experience</p><h1 id="visual-experience-title">{title}</h1></div>
        {visual.association.authoredFixture ? <span>Authored fixture</span> : null}
      </header>
      {visual.association.fixtureLabel ? <p className={styles.fixtureNote}>{visual.association.fixtureLabel}. This demonstration was explicitly authored and was not generated by AI.</p> : null}
      {visual.association.blueprint.scenes.length > 1 ? (
        <nav className={styles.sceneNavigation} aria-label="Lesson scenes">
          {visual.association.blueprint.scenes.map((item, index) => <button type="button" key={item.id} aria-current={index === sceneIndex ? "step" : undefined} onClick={() => setSceneIndex(index)}>Part {index + 1}</button>)}
        </nav>
      ) : null}
      <VisualScenePlayer key={scene.id} scene={scene} narrationMedia={narrationMedia} />
      {!completeAudio ? <p className={styles.audioFallback} role="status">Narration is not available for every segment. Captions and animation remain available.</p> : null}
    </section>
  );
}
